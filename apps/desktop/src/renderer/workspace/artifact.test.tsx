import assert from "node:assert/strict";
import { it } from "node:test";
import { renderToStaticMarkup } from "react-dom/server";
import { CanvasSchema } from "../../shared/contracts";
import { ArtifactCanvas } from "./ArtifactCanvas";

it("renders every validated visual primitive as an actual SVG image with escaped text", () => {
	const canvas = CanvasSchema.parse({
		kind: "visual",
		id: "visual-1",
		title: "Proposed layout",
		revision: 1,
		provenance: "agent-draft",
		visual: {
			width: 800,
			height: 600,
			background: "#ffffff",
			elements: [
				{ kind: "rect", x: 20, y: 30, width: 200, height: 100, fill: "#112233", radius: 8 },
				{
					kind: "text",
					x: 30,
					y: 65,
					text: "<script>actual supplied text</script>",
					fill: "#ffffff",
					fontSize: 16,
					weight: "bold",
				},
				{ kind: "line", x: 20, y: 160, x2: 220, y2: 160, stroke: "#445566", width: 2 },
			],
		},
	});
	assert.equal(canvas.kind, "visual");
	if (canvas.kind !== "visual") throw new Error("Expected visual");
	const html = renderToStaticMarkup(<ArtifactCanvas canvas={canvas} />);
	assert.match(html, /<svg[^>]+viewBox="0 0 800 600"[^>]+role="img"/);
	assert.match(html, /<rect x="20" y="30" width="200" height="100" rx="8" fill="#112233"/);
	assert.match(html, /<line x1="20" y1="160" x2="220" y2="160" stroke="#445566" stroke-width="2"/);
	assert.match(html, /&lt;script&gt;actual supplied text&lt;\/script&gt;/);
	assert.match(html, /Visual mockup.*agent draft/);
	assert.doesNotMatch(html, /<script|<image|<foreignObject|<iframe|Generated by|Executed/);
	assert.throws(() =>
		CanvasSchema.parse({
			...canvas,
			visual: { ...canvas.visual, elements: [{ kind: "image", href: "javascript:attack" }] },
		})
	);
	assert.throws(() =>
		CanvasSchema.parse({
			...canvas,
			visual: { ...canvas.visual, background: "url(https://example.com/track)" },
		})
	);
});

it("renders supplied document content, revision and full pinned reference identity", () => {
	const canvas = CanvasSchema.parse({
		kind: "document",
		id: "doc-1",
		title: "Actual explanation",
		revision: 3,
		provenance: "agent-draft",
		markdown: "## Supplied heading\n\nAn actual **finding**.",
		references: [
			{
				repository: "owner/project",
				path: "src/entry.ts",
				revision: "head",
				commitSha: "b".repeat(40),
				startLine: 4,
				endLine: 8,
			},
		],
	});
	if (canvas.kind !== "document") throw new Error("Expected document");
	const html = renderToStaticMarkup(<ArtifactCanvas canvas={canvas} />);
	assert.match(html, /data-artifact-revision="3"/);
	assert.match(html, /<h2>Supplied heading<\/h2>/);
	assert.match(html, /An actual <strong>finding<\/strong>/);
	assert.match(html, /src\/entry.ts:4–8/);
	assert.match(html, /head · bbbbbbbb/);
});
