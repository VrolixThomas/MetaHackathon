import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const names = ["muse-team-api", "muse-team-webhook", "muse-team-worker"];
for (const name of names) {
	const built = await Bun.build({
		entrypoints: [join(root, "services/team/edge", `${name}.ts`)],
		format: "esm",
		target: "browser",
		external: ["node:*"],
		sourcemap: "none",
		minify: false,
		env: "disable",
	});
	const output = built.outputs[0];
	if (!built.success || built.outputs.length !== 1 || !output)
		throw new Error(`Edge build failed for ${name}`);
	const code = await output.text();
	if (Buffer.byteLength(code) > 5_000_000)
		throw new Error(`Edge bundle exceeds server deployment limit: ${name}`);
	const destination = join(root, "supabase/functions", name, "index.ts");
	await mkdir(dirname(destination), { recursive: true });
	await writeFile(
		destination,
		`// Generated by services/team/build-edge.mjs; edit the versioned source.\n${code}`
	);
	console.log(`${name}: ${Buffer.byteLength(code)} bytes`);
}
